#!/usr/bin/env node
/// <reference types="node" />

// Generates type-only schemas for `@gadgets/gatekeeper-kit/http` from an OpenAPI document, with the
// Forge plugin in ../forge: one `.d.ts` per group, each with that group's models and an `Api` schema.
//
//     gatekeeper-openapi-schema <spec> --out <dir> [--group-by tag] [--operations <file>]
//                               [--omit-header <name>]... [--writable <property>]... [--patch <file>]
//
// <spec> is a JSON file or an https URL. --operations names a file listing the operationIds to
// keep, one per line (`#` starts a comment); every other operation is left out. --group-by tag
// groups each operation by its first tag, for documents without Forge's own `x-forge-group-name`.
// --omit-header drops a header parameter, by name in any case, from every operation: one the
// client sends itself, through its `headers` or `fetch` option, so calls need not pass it.
// --writable clears `readOnly` from every property of that name, for a document that marks a field
// read-only although requests send it, such as an `id` that references must name. --patch applies a
// JSON Patch (RFC 6902) file of `add`, `replace` and `remove` operations to the document first, to
// correct what it gets wrong; each operation may say why in a `reason`, which is ignored.
// The output directory holds only generated files: they are replaced on each run, and a file in it
// that Forge did not write stops the run.

import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { once } from "node:events";
import {
  existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const GENERATED_PREAMBLE = "// Code generated by forge. DO NOT EDIT.";
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

const usage = "usage: gatekeeper-openapi-schema <spec> --out <dir> [--group-by tag] " +
  "[--operations <file>] [--omit-header <name>]... [--writable <property>]... [--patch <file>]";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

function fail(message: string): never {
  process.stderr.write(`gatekeeper-openapi-schema: ${message}\n`);
  process.exit(1);
}

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

const { values, positionals } = (() => {
  try {
    return parseArgs({
      allowPositionals: true,
      options: {
        out: { type: "string" },
        "group-by": { type: "string" },
        operations: { type: "string" },
        "omit-header": { type: "string", multiple: true },
        writable: { type: "string", multiple: true },
        patch: { type: "string" },
      },
    });
  } catch (error) {
    fail(`${(error as Error).message}\n${usage}`);
  }
})();
if (positionals.length !== 1 || values.out === undefined) fail(usage);
if (values["group-by"] !== undefined && values["group-by"] !== "tag") {
  fail(`--group-by takes only "tag"\n${usage}`);
}

const kitDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const forgeDir = dirname(createRequire(import.meta.url).resolve("@cloudflare/forge/package.json"));

await main(positionals[0], values.out, values["group-by"] === "tag", values.operations,
  values["omit-header"] ?? [], values.writable ?? [], values.patch);

async function main(
  spec: string, outArg: string, byTag: boolean, operationsFile: string | undefined,
  omittedHeaders: readonly string[], writable: readonly string[], patchFile: string | undefined,
): Promise<void> {
  const doc = await readDocument(spec);
  if (patchFile !== undefined) applyPatch(doc, JSON.parse(readFileSync(patchFile, "utf8")) as Json, patchFile);
  if (operationsFile !== undefined) keepOperations(doc, readOperationIds(operationsFile));
  prepareOperations(doc, byTag);
  omitHeaders(doc, new Set(omittedHeaders.map(name => name.toLowerCase())));
  inlineInnerRefs(doc);
  clearReadOnly(doc, new Set(writable));
  renameCollidingProperties(doc);

  const wasm = buildPlugin();
  const outDir = resolve(outArg);
  // Beside the output, so the finished directory moves into place with a rename.
  mkdirSync(dirname(outDir), { recursive: true });
  const stagingDir = mkdtempSync(join(dirname(outDir), ".openapi-schema-"));
  try {
    await runForge(doc, wasm, stagingDir);
    replaceOutput(stagingDir, outDir);
  } finally {
    rmSync(stagingDir, { recursive: true, force: true });
  }
  process.stderr.write(`gatekeeper-openapi-schema: wrote ${relative(process.cwd(), outDir) || "."}\n`);
}

async function readDocument(spec: string): Promise<JsonObject> {
  let text: string;
  if (spec.startsWith("https://")) {
    const response = await fetch(spec);
    if (!response.ok) fail(`fetching ${spec} failed with status ${response.status}`);
    text = await response.text();
  } else {
    text = readFileSync(spec, "utf8");
  }
  const parsed = JSON.parse(text) as Json;
  if (!isObject(parsed) || !isObject(parsed.paths)) fail(`${spec} is not an OpenAPI document`);
  return parsed;
}

/**
 * Applies a JSON Patch (RFC 6902) to `document`: its `add`, `replace` and `remove` operations, in
 * order. Any other operation, or a path that does not resolve, stops the run.
 */
function applyPatch(document: JsonObject, patch: Json, file: string): void {
  if (!Array.isArray(patch)) fail(`${file} is not a JSON Patch: an array of operations`);
  patch.forEach((operation, index) => {
    const where = `${file} operation ${index}`;
    if (!isObject(operation) || typeof operation.op !== "string" || typeof operation.path !== "string") {
      fail(`${where} needs an op and a path`);
    }
    const { op, path } = operation;
    if (!path.startsWith("/")) fail(`${where}: path ${path} is not a JSON Pointer to a member`);
    const keys = path.slice(1).split("/").map(key => key.replaceAll("~1", "/").replaceAll("~0", "~"));
    const last = keys.pop()!;
    let parent: Json | undefined = document;
    for (const key of keys) {
      parent = Array.isArray(parent) ? parent[Number(key)] : isObject(parent) ? parent[key] : undefined;
    }
    if (!Array.isArray(parent) && !isObject(parent)) fail(`${where}: nothing at ${path}'s parent`);
    const exists = Array.isArray(parent) ? Number(last) < parent.length : Object.hasOwn(parent, last);
    if (op !== "add" && !exists) fail(`${where}: nothing at ${path} to ${op}`);
    if (op !== "remove" && !("value" in operation)) fail(`${where} needs a value`);
    if (op !== "add" && op !== "replace" && op !== "remove") fail(`${where}: op ${op} is not add, replace or remove`);
    if (Array.isArray(parent)) {
      const at = last === "-" ? parent.length : Number(last);
      if (!Number.isInteger(at) || at < 0 || at > parent.length) fail(`${where}: ${path} is not an index`);
      if (op === "add") parent.splice(at, 0, operation.value!);
      else if (op === "replace") parent[at] = operation.value!;
      else parent.splice(at, 1);
    } else if (op === "remove") {
      delete parent[last];
    } else {
      parent[last] = operation.value!;
    }
  });
}

function readOperationIds(path: string): Set<string> {
  return new Set(readFileSync(path, "utf8").split("\n")
    .map(line => line.replace(/#.*/, "").trim())
    .filter(line => line !== ""));
}

/** Each operation in the document, with the path item and method holding it. */
function* operations(document: JsonObject): Generator<[JsonObject, string, JsonObject]> {
  for (const item of Object.values(document.paths as JsonObject)) {
    if (!isObject(item)) continue;
    for (const method of HTTP_METHODS) {
      const operation = item[method];
      if (isObject(operation)) yield [item, method, operation];
    }
  }
}

/** Removes every operation `ids` does not name, and fails on an id the document lacks. */
function keepOperations(document: JsonObject, ids: Set<string>): void {
  const found = new Set<string>();
  for (const [item, method, operation] of operations(document)) {
    const id = operation.operationId;
    if (typeof id === "string" && ids.has(id)) {
      found.add(id);
    } else {
      delete item[method];
    }
  }
  const missing = [...ids].filter(id => !found.has(id));
  if (missing.length > 0) fail(`the document has no operation ${missing.join(", ")}`);
  const paths = document.paths as JsonObject;
  for (const [path, item] of Object.entries(paths)) {
    if (isObject(item) && !HTTP_METHODS.some(method => method in item)) delete paths[path];
  }
}

/**
 * Copies each operationId into `x-operation-id`, which Forge hands the plugin for its comments,
 * and with `byTag`, groups each operation by its first tag.
 */
function prepareOperations(document: JsonObject, byTag: boolean): void {
  for (const [, method, operation] of operations(document)) {
    const id = operation.operationId;
    if (typeof id === "string") operation["x-operation-id"] = id;
    if (!byTag || "x-forge-method-name" in operation) continue;
    const tag = Array.isArray(operation.tags) ? operation.tags[0] : undefined;
    if (typeof tag !== "string") continue;
    operation["x-forge-group-name"] = tag;
    operation["x-forge-method-name"] = typeof id === "string" ? id : method;
  }
}

/**
 * Removes the header parameters `names` names, lower-cased, from every operation and path item,
 * resolving parameters that refer to `components.parameters`.
 */
function omitHeaders(document: JsonObject, names: Set<string>): void {
  if (names.size === 0) return;
  const components = isObject(document.components) && isObject(document.components.parameters)
    ? document.components.parameters : {};
  const resolveRef = (parameter: Json): Json | undefined => {
    if (!isObject(parameter) || typeof parameter.$ref !== "string") return parameter;
    const prefix = "#/components/parameters/";
    if (!parameter.$ref.startsWith(prefix)) return undefined;
    return components[parameter.$ref.slice(prefix.length).replaceAll("~1", "/").replaceAll("~0", "~")];
  };
  const omitted = (parameter: Json): boolean => {
    const resolved = resolveRef(parameter);
    return isObject(resolved) && resolved.in === "header" && typeof resolved.name === "string" &&
      names.has(resolved.name.toLowerCase());
  };
  const owners = [...Object.values(document.paths as JsonObject).filter(isObject),
    ...[...operations(document)].map(([, , operation]) => operation)];
  for (const owner of owners) {
    if (Array.isArray(owner.parameters)) owner.parameters = owner.parameters.filter(p => !omitted(p));
  }
}

/** Clears `readOnly` from every property, in any schema, that `names` names. */
function clearReadOnly(value: Json, names: Set<string>): void {
  if (names.size === 0) return;
  if (Array.isArray(value)) {
    for (const item of value) clearReadOnly(item, names);
    return;
  }
  if (!isObject(value)) return;
  if (isObject(value.properties)) {
    for (const [name, property] of Object.entries(value.properties)) {
      if (names.has(name) && isObject(property)) delete property.readOnly;
    }
  }
  for (const item of Object.values(value)) clearReadOnly(item, names);
}

/** Whether `ref` points inside a component other than a schema, rather than at a whole one. */
function isInnerRef(ref: string): boolean {
  const segments = ref.split("/");
  return ref.startsWith("#/components/") && segments[2] !== "schemas" && segments.length > 4;
}

/**
 * Replaces each `$ref` to a part of a component other than a schema, such as
 * `#/components/responses/Conflict/content/application~1json/schema`, with a copy of what it
 * points to. Forge follows `$ref`s to whole components and into `components.schemas` only.
 */
function inlineInnerRefs(document: JsonObject): void {
  const target = (ref: string): Json | undefined => {
    let value: Json | undefined = document;
    for (const segment of ref.slice(2).split("/")) {
      const key = segment.replaceAll("~1", "/").replaceAll("~0", "~");
      value = Array.isArray(value) ? value[Number(key)] : isObject(value) ? value[key] : undefined;
    }
    return value;
  };
  const inline = (value: Json, inlining: readonly string[]): Json => {
    if (Array.isArray(value)) return value.map(item => inline(item, inlining));
    if (!isObject(value)) return value;
    const ref = value.$ref;
    if (typeof ref === "string" && isInnerRef(ref)) {
      if (inlining.includes(ref)) fail(`$ref "${ref}" refers to itself`);
      const resolved = target(ref);
      if (resolved === undefined) fail(`$ref "${ref}" points to nothing`);
      return inline(structuredClone(resolved), [...inlining, ref]);
    }
    for (const [key, item] of Object.entries(value)) value[key] = inline(item, inlining);
    return value;
  };
  inline(document, []);
}

/**
 * Forge names a property by its words, which it reads from letters and digits, so `+1` and `-1`
 * are both `1` and collide. The plugin keys objects by wire name, so colliding properties are given
 * names Forge keeps apart: the hex of their wire names.
 */
function renameCollidingProperties(value: Json): void {
  if (Array.isArray(value)) {
    value.forEach(renameCollidingProperties);
    return;
  }
  if (!isObject(value)) return;
  const properties = value.properties;
  if (isObject(properties)) {
    const byWords = new Map<string, string[]>();
    for (const name of Object.keys(properties)) {
      const words = forgeWords(name);
      byWords.set(words, [...byWords.get(words) ?? [], name]);
    }
    for (const names of byWords.values()) {
      if (names.length < 2) continue;
      for (const name of names) {
        const property = properties[name];
        if (isObject(property) && !("x-forge-property-name" in property)) {
          property["x-forge-property-name"] = `p${Buffer.from(name).toString("hex")}`;
        }
      }
    }
  }
  Object.values(value).forEach(renameCollidingProperties);
}

/** Roughly the words Forge reads from a name: runs of letters and digits, split at camelCase. */
function forgeWords(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase()
    .split(/[^a-z0-9]+/).filter(Boolean).join(" ");
}

/** Builds the plugin component, unless one built from the same sources is cached. */
function buildPlugin(): string {
  const sources = ["forge/plugin.ts", "forge/emit.ts"].map(path => join(kitDir, path));
  const hash = createHash("sha256");
  for (const path of [...sources, join(forgeDir, "package.json")]) hash.update(readFileSync(path));
  const cacheDir = join(kitDir, "node_modules", ".cache", "openapi-schema");
  const wasm = join(cacheDir, `plugin-${hash.digest("hex").slice(0, 16)}.wasm`);
  if (existsSync(wasm)) return wasm;

  mkdirSync(cacheDir, { recursive: true });
  for (const stale of readdirSync(cacheDir)) rmSync(join(cacheDir, stale), { force: true });
  const result = spawnSync(process.execPath,
    [join(forgeDir, "bin", "forge-plugin.mjs"), "build", sources[0], "-o", wasm],
    { stdio: ["ignore", "inherit", "inherit"] });
  if (result.status !== 0 || !existsSync(wasm)) fail("building the Forge plugin failed");
  return wasm;
}

async function runForge(document: JsonObject, plugin: string, outDir: string): Promise<void> {
  const forge = spawn(process.execPath,
    [join(forgeDir, "bin", "forge.cjs"), "-", "--target", `wasm://${plugin}`, "--out", outDir],
    { stdio: ["pipe", "inherit", "inherit"] });
  const [[code], ] = await Promise.all([
    once(forge, "close") as Promise<[number | null]>,
    pipeline(Readable.from([JSON.stringify(document)]), forge.stdin),
  ]);
  if (code !== 0) fail(`forge exited with ${code}`);
}

/** Replaces the generated files in `out` with those in `staging`. */
function replaceOutput(staging: string, out: string): void {
  if (existsSync(out)) {
    for (const path of filesIn(out)) {
      if (!readFileSync(path, "utf8").startsWith(GENERATED_PREAMBLE)) {
        fail(`${relative(process.cwd(), path)} was not generated; the output directory must hold ` +
          "only generated files");
      }
    }
    rmSync(out, { recursive: true });
  }
  renameSync(staging, out);
}

function filesIn(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile())
    .map(entry => join(entry.parentPath, entry.name));
}
